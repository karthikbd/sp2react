def generate(out: Path, specs: list[Spec], legacy: Legacy, export_dir: Optional[Path] = None,
             data_source: str = "sqlite", mapping_file: Optional[Path] = None) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    written = copy_templates(out)
    (out / "backend" / "specs").mkdir(parents=True, exist_ok=True)
    (out / "frontend" / "src" / "specs").mkdir(parents=True, exist_ok=True)
    for s in specs:
        js = s.model_dump_json(indent=2, exclude_none=True)
        (out / "backend" / "specs" / f"{s.screen.id}.json").write_text(js, encoding="utf-8")
        (out / "frontend" / "src" / "specs" / f"{s.screen.id}.json").write_text(js, encoding="utf-8")

    seed_dir = out / "backend" / "data" / "seed"
    seed_dir.mkdir(parents=True, exist_ok=True)
    counts, lists_done = {}, set()
    for s in specs:
        for name, l in s.lists.items():
            if name in lists_done:
                continue
            lists_done.add(name)
            rows = seed_rows(legacy, name, l.fields, export_dir)
            counts[name] = len(rows)
            (seed_dir / f"{name}.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
            if export_dir and (export_dir / "attachments" / name).exists():
                dst = out / "backend" / "data" / "attachments" / name
                if dst.exists():
                    shutil.rmtree(dst)
                shutil.copytree(export_dir / "attachments" / name, dst)
    (out / "backend" / "data" / "users.json").write_text(json.dumps(users_json(legacy), indent=2), encoding="utf-8")

    src = out / "frontend" / "src"
    (src / "site.ts").write_text(site_ts(legacy, specs), encoding="utf-8")
    (src / "App.tsx").write_text(app_tsx(specs, out), encoding="utf-8")
    (src / "custom" / "index.ts").write_text(custom_index(out), encoding="utf-8")
    (src / "styles" / "legacy.css").write_text(legacy_css(legacy, specs), encoding="utf-8")
    html = (out / "frontend" / "index.html").read_text(encoding="utf-8").replace("__SITE_TITLE__", legacy.site.get("title") or "Site")
    (out / "frontend" / "index.html").write_text(html, encoding="utf-8")
    (out / "backend" / "tests" / "test_generated.py").write_text(generated_tests(specs, counts, data_source), encoding="utf-8")
    main_py = out / "backend" / "app" / "main.py"
    main_py.write_text(main_py.read_text(encoding="utf-8").replace("__DEFAULT_SOURCE__", data_source), encoding="utf-8")
    if data_source == "database":
        if mapping_file and mapping_file.exists():
            shutil.copyfile(mapping_file, out / "backend" / "mapping.json")
        roles = out / "backend" / "data" / "roles.json"
        if not roles.exists():   # SharePoint group names; members are filled in by your admins (or come from the users table)
            groups = sorted({r for sp in specs for r in sp.roles} | {g["name"] for g in legacy.site.get("groups", [])})
            roles.write_text(json.dumps({g: [] for g in groups}, indent=2), encoding="utf-8")
    (out / "backend" / ".env.example").write_text(ENV_EXAMPLE.replace("__SOURCE__", data_source), encoding="utf-8")
    shared = TEMPLATES.parent / "rule_vectors.json"
    if shared.exists():
        (out / "shared").mkdir(exist_ok=True)
        shutil.copyfile(shared, out / "shared" / "rule_vectors.json")
    return {"files": len(written) + 8 + 2 * len(specs), "seed": counts}


def refresh_registries(out: Path, specs: list[Spec]) -> None:
    """After agents add files: re-link App.tsx routes and the custom handler registry."""
    src = out / "frontend" / "src"
    (src / "App.tsx").write_text(app_tsx(specs, out), encoding="utf-8")
    (src / "custom" / "index.ts").write_text(custom_index(out), encoding="utf-8")
