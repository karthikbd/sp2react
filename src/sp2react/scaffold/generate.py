"""Stage 6a: deterministic code generation (seconds, no model calls).

Writes the React + FastAPI app skeleton, the specs, seed data and generated tests. Agents only
write what is screen-specific (page components, custom handlers); everything here is fixed code.
"""
from __future__ import annotations

